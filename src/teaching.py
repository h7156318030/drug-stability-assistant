# ----------------------------------------------------------------------------
# 常见误区提示
# ----------------------------------------------------------------------------
PITFALLS = [
    "误将强制降解的降解速率当作真实货架期预测 → 强制降解仅用于方法确证。",
    "生物制品套用化药5%显著变化标准 → 效价>10% 或纯度下降应专属判定(Q5C)。",
    "仅1批即外推2倍有效期 → Q1E 要求至少3批且覆盖75%监测期。",
    "忽略 DS 稳定性 → DS 是 DP 有效期与运输条件的上游支撑。",
    "使用中(in-use)稳定性缺失 → 复溶后存放时间是临床给药安全前提。",
    "矩阵法未论证即缩减 → Q1D 要求统计学论证并增加不确定性。",
    "加速数据直接换算长期有效期 → 仅当 Arrhenius 关系成立且经确证。",
]


def checklist_for(stage: str) -> list:
    """返回指定阶段的合规检查清单（模糊匹配）。"""
    for k, v in CHECKLISTS.items():
        if stage and stage in k:
            return v
    return CHECKLISTS.get("I期临床", [])


